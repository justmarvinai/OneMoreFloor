/**
 * Vendor the paperdoll's slot icons from Open Game Icons.
 *
 * Each empty gear socket carries a faint picture of what it takes, so a player
 * can read the paperdoll without hovering every hole in it. The icons come from
 * https://github.com/open-game-icons/icons (CC BY 3.0, or CC0 for some
 * contributors) — vendored, never fetched: the game makes no network request
 * after its own load (Brief §21).
 *
 * Game-icons SVGs ship as a black square with a white glyph on it. That is a
 * picture, and we want a *mask*, so this strips the background rect and repaints
 * the glyph as `currentColor` — the same shape FantasyUI's own `glyph-*` set
 * uses, which is what lets the socket tint the icon with the theme's ink and
 * drop it to a whisper of opacity.
 *
 * Run with a local clone of the icon repo:
 *
 *   OGI_SRC=/path/to/open-game-icons/icons node tools/vendor-slot-icons.mjs
 *
 * It writes `public/art/slots/*.svg`, the stylesheet that binds them to slot
 * ids, and the attribution file the licence asks for. All three are committed,
 * so a normal checkout never needs the clone.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.env.OGI_SRC ?? resolve(ROOT, '../justmarvinai/open-game-icons');
const OUT_DIR = join(ROOT, 'public/art/slots');

/**
 * One icon per equip slot, chosen to be readable at 40px and unmistakable
 * against its neighbours — the ring and the necklace especially, since they sit
 * next to each other in the ascension column.
 */
const ICONS = [
  { slot: 'helmet', file: 'lorc/visored-helm.svg', author: 'Lorc' },
  { slot: 'chest', file: 'lorc/armor-vest.svg', author: 'Lorc' },
  { slot: 'gauntlets', file: 'delapouite/gauntlet.svg', author: 'Delapouite' },
  { slot: 'wrists', file: 'skoll/bracers.svg', author: 'Skoll' },
  { slot: 'leggings', file: 'delapouite/leg-armor.svg', author: 'Delapouite' },
  { slot: 'boots', file: 'lorc/leather-boot.svg', author: 'Lorc' },
  { slot: 'cape', file: 'delapouite/cape.svg', author: 'Delapouite' },
  { slot: 'ring', file: 'delapouite/ring.svg', author: 'Delapouite' },
  { slot: 'necklace', file: 'lorc/gem-pendant.svg', author: 'Lorc' },
  { slot: 'amulet', file: 'lorc/emerald.svg', author: 'Lorc' },
  { slot: 'relic', file: 'delapouite/crystal-shrine.svg', author: 'Delapouite' },
  { slot: 'artifact', file: 'lorc/eclipse-flare.svg', author: 'Lorc' },
  { slot: 'mainhand', file: 'lorc/broadsword.svg', author: 'Lorc' },
  { slot: 'offhand', file: 'willdabeast/round-shield.svg', author: 'Willdabeast' },
];

/** The black backdrop every game-icons SVG opens with. */
const BACKDROP = /<path d="M0 0h512v512H0z"[^>]*\/>/;

function toMask(source, file) {
  if (!BACKDROP.test(source)) {
    throw new Error(`[slot-icons] ${file} has no backdrop rect to strip — check the source format`);
  }
  const glyph = source.replace(BACKDROP, '').replaceAll('fill="#fff"', 'fill="currentColor"');
  if (glyph.includes('#fff')) {
    throw new Error(`[slot-icons] ${file} still has a hard-coded white after conversion`);
  }
  return `${glyph.trim()}\n`;
}

mkdirSync(OUT_DIR, { recursive: true });

const lines = [];
for (const { slot, file, author } of ICONS) {
  const source = readFileSync(join(SRC, file), 'utf8');
  writeFileSync(join(OUT_DIR, `${slot}.svg`), toMask(source, file));
  lines.push({ slot, file, author });
}

writeFileSync(
  join(ROOT, 'src/styles/slots.css'),
  `/**
 * Slot-type icons for empty gear sockets.
 *
 * GENERATED by \`tools/vendor-slot-icons.mjs\` — edit that, not this.
 *
 * They are masks rather than pictures, so the socket tints them with the panel's
 * own ink and holds them at a whisper: a full-strength icon in every empty hole
 * would read as fourteen items the player does not have (§20.1).
 */
${lines
  .map(
    ({ slot }) => `.omf-character__doll .fui-slot--empty[data-slot-id='${slot}']::after {
  --omf-slot-icon: url('/art/slots/${slot}.svg');
}`,
  )
  .join('\n\n')}
`,
);

writeFileSync(
  join(ROOT, 'public/art/slots/ATTRIBUTION.md'),
  `# Slot icons — attribution

These fourteen icons come from [Open Game Icons](https://open-game-icons.net)
(\`github.com/open-game-icons/icons\`), which is licensed **CC BY 3.0**, with some
contributors releasing under CC0. Attribution is required for the CC BY ones, and
is given here and in \`docs/CREDITS.md\`.

They are used as masks: the black backdrop each source file carries is stripped
and the glyph repainted as \`currentColor\` (\`tools/vendor-slot-icons.mjs\`). That
is a derivative work, which the licence permits.

| Slot | Icon | Author |
|---|---|---|
${lines.map(({ slot, file, author }) => `| ${slot} | \`${file}\` | ${author} |`).join('\n')}
`,
);

console.warn(`[slot-icons] vendored ${lines.length} icons from ${SRC}`);
